/**
 * Secondary-label translations for the partner listing form.
 *
 * Every field on /partner-listing shows its English label first and, underneath,
 * the same label in the visitor's country language — resolved from the country
 * code `basicStore` already derives (auth profile, else IP). English-speaking
 * countries resolve to `null` and get one label, not two identical ones.
 *
 * WHY THIS IS NOT NUXT-I18N
 * Nothing else on www-v3 is translated and nothing else is planned to be. This
 * is one form's worth of field labels, always rendered ALONGSIDE the English —
 * the English is the source of truth and a missing or imperfect translation
 * degrades to "English only", never to a broken page. A full i18n runtime would
 * add a module, a locale-routing strategy and a build step to serve twenty
 * nouns.
 *
 * WHY COUNTRY AND NOT navigator.language
 * The browser language is the language of the device, which in these markets is
 * very often English even when the user is not comfortable reading a business
 * form in it — a Philippine retailer on an English-locale Android is exactly the
 * person this feature is for. Country is the better proxy, and it is the signal
 * the rest of the site already resolves.
 *
 * ADDING A LANGUAGE
 * Add the twenty strings under a BCP-47 key in LABELS, then point countries at
 * it in COUNTRY_LOCALE. Nothing else needs to change; an unmapped country keeps
 * working on English alone. Day names are NOT in here — Intl.DateTimeFormat
 * produces those from the same locale tag, correctly, for free.
 */

