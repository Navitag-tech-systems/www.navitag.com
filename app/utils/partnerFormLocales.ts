/** BCP-47 tag for a country, or null when the country reads the English labels. */
export function resolveFormLocale(countryCode: string | null | undefined): string | null {
  if (!countryCode) return null
  const tag = COUNTRY_LOCALE[countryCode.toUpperCase()]
  return tag && LABELS[tag] ? tag : null
}

/** Secondary labels for a locale tag, or null. */
export function secondaryLabels(locale: string | null): PartnerFormLabels | null {
  return locale ? (LABELS[locale] ?? null) : null
}

/**
 * Localised Monday-first weekday names for the hours grid.
 *
 * Built from Intl rather than from the dictionary above: the browser already
 * ships correct weekday names for every locale, so hand-translating seven more
 * strings per language would add 200-odd entries that can only be wrong.
 * 2024-01-01 is a Monday, which is what makes the offset arithmetic honest.
 */
export function weekdayNames(locale: string, style: 'long' | 'short' = 'long'): string[] {
  try {
    const fmt = new Intl.DateTimeFormat(locale, { weekday: style })
    return Array.from({ length: 7 }, (_, i) =>
      fmt.format(new Date(Date.UTC(2024, 0, 1 + i))),
    )
  }
  catch {
    // Unknown tag, or an engine without full ICU — the caller falls back to the
    // English names it already has.
    return []
  }
}
